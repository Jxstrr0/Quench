/**
 * The service worker's source, written into the build as sw.js by
 * vite.config.ts. It is what lets the game play with no connection.
 *
 * - Every file of the game (page, code, styles, fonts, models, sounds, icons)
 *   is stored when the worker installs, so one visit is enough: the whole of
 *   dist/ is small (the build holds it under 6 MB).
 * - Stored files are served from the store. The page itself comes from the
 *   network when there is one, so a new deploy is seen at once, and from the
 *   store when there is none.
 * - Each build has its own store, named `quench-<build>`. A new build's
 *   worker waits until the player taps Reload (src/ui/offline.ts), then takes
 *   over and clears the older `quench-` stores. It never touches a store with
 *   any other name.
 */
export const STORE_PREFIX = 'quench-'

export function serviceWorkerSource(build: string, files: readonly string[]): string {
  return `// Quench service worker, build ${build}. Generated by vite.config.ts.
const PREFIX = ${JSON.stringify(STORE_PREFIX)};
const STORE = PREFIX + ${JSON.stringify(build)};
const FILES = ${JSON.stringify(['./', ...files])};
const KEPT = new Set(FILES.map((f) => new URL(f, self.registration.scope).pathname));
const ANY = { ignoreSearch: true, ignoreVary: true };

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(STORE).then((c) => Promise.all(FILES.map((u) => c.add(new Request(u, { cache: 'reload' }))))));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith(PREFIX) && k !== STORE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('message', (e) => {
  if (e.data === 'skip-waiting') self.skipWaiting();
});

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin || !url.pathname.startsWith(new URL(self.registration.scope).pathname)) return;
  const page = req.mode === 'navigate';
  e.respondWith(
    caches.open(STORE).then(async (c) => {
      // A stored file belongs to this build: the stored copy is always the right one,
      // whatever the address was tagged with and whatever headers the server said it varies by.
      if (!page && KEPT.has(url.pathname)) {
        const hit = await c.match(req, ANY);
        if (hit) return hit;
      }
      try {
        const res = await fetch(req);
        if (res.status === 200 && res.type === 'basic' && !page) c.put(req, res.clone()).catch(() => {});
        return res;
      } catch (err) {
        const hit = await c.match(page ? './' : req, ANY);
        if (hit) return hit;
        throw err;
      }
    }),
  );
});
`
}

/**
 * The built files the worker stores: all of them, but for the worker itself,
 * source maps, and the old-format copies of the fonts (every browser that can
 * run a service worker reads woff2).
 */
export function offlineFiles(names: readonly string[]): string[] {
  const kept = names.filter((n) => n !== 'sw.js' && n !== 'index.html' && !n.endsWith('.map') && !n.endsWith('.woff') && !n.startsWith('.') && !n.includes('/.'))
  return [...new Set(kept)].sort()
}

/** A short name for a build, from the names and contents that make it up. The same build always gets the same one. */
export function buildId(parts: readonly string[]): string {
  let hash = 5381
  for (const part of parts) {
    for (let i = 0; i < part.length; i++) hash = (hash * 33 + part.charCodeAt(i)) >>> 0
    hash = (hash * 33 + 10) >>> 0
  }
  return hash.toString(36)
}
